/** Constructed languages have no country, so they are listed on their own. */
export const UNASSIGNED: readonly string[] = ["eo", "ie", "ido", "tlh"]

const BY_LANGUAGE = new Map(LANGUAGES.map((entry) => [entry.code, entry]))

/**
 * Resolve the language codes a country lists to the entries we can render.
 *
 * The table names each language by the exact code we define it under, so this is
 * a straight lookup and nothing else: a code with no entry is a bug in the table,
 * not something to paper over. Duplicates are dropped because several countries
 * list a language both by its regional tag and its base tag.
 */
function resolve(codes: readonly string[]) {
  const seen = new Set<string>()
  return codes.flatMap((code) => {
    const entry = BY_LANGUAGE.get(code)
    if (!entry || seen.has(entry.code)) return []
    seen.add(entry.code)
    return [entry]
  })
}

export const COUNTRIES: readonly Country[] = Object.entries(NAMES)
  .map(([code, [name, native]]) => ({
    code,
    name,
    native,
    flag: countryFlag(code),
    languages: resolve(BY_COUNTRY[code] ?? []),
  }))
  .sort((a, b) => a.name.localeCompare(b.name))

export function countryLanguages(code: string) {
  return COUNTRIES.find((country) => country.code === code)?.languages ?? []
}

export function searchCountries(query: string) {
  const needle = query.trim().toLowerCase()
  if (!needle) return COUNTRIES
  return COUNTRIES.filter(
    (country) =>
      country.name.toLowerCase().includes(needle) ||
      country.native.toLowerCase().includes(needle) ||
      country.code.toLowerCase() === needle ||
      country.languages.some((language) => language.native.toLowerCase().includes(needle)),
  )
}