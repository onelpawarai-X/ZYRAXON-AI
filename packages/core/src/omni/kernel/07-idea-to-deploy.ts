export class IdeaToDeploy {
  private generatedProjects: Map<string, { path: string; type: string; createdAt: number; fileCount: number }> = new Map()
  private buildHistory: Array<{ project: string; success: boolean; duration: number; timestamp: number }> = []

  async createProject(name: string, type: string = "web", projectDir?: string): Promise<string> {
    const template = TEMPLATES[type] ?? WEB_TEMPLATE
    const dir = projectDir ?? join(process.cwd(), name)
    mkdirSync(dir, { recursive: true })
    for (const file of template.files) {
      const filePath = join(dir, file.path)
      const fileDir = filePath.substring(0, filePath.lastIndexOf("/"))
      if (fileDir) mkdirSync(fileDir, { recursive: true })
      const content = file.content.replace(/\{\{name\}\}/g, name)
      writeFileSync(filePath, content)
    }
    const packageJsonPath = join(dir, "package.json")
    if (existsSync(packageJsonPath)) {
      const content = readFileSync(packageJsonPath, "utf-8")
      const pkg = JSON.parse(content)
      pkg.name = name
      pkg.scripts = { ...pkg.scripts, ...template.scripts }
      writeFileSync(packageJsonPath, JSON.stringify(pkg, null, 2))
    }
    this.generatedProjects.set(name, { path: dir, type, createdAt: Date.now(), fileCount: template.files.length })
    return dir
  }

  async deployToGitHubPages(projectDir: string): Promise<DeploymentResult> {
    const startTime = performance.now()
    const { execSync } = await import("node:child_process")
    try {
      execSync("git init", { cwd: projectDir, stdio: "pipe" })
      execSync("git add -A", { cwd: projectDir, stdio: "pipe" })
      execSync('git commit -m "initial: auto-deployed by ZYRAXON AI"', { cwd: projectDir, stdio: "pipe" })
      const buildTime = performance.now() - startTime
      const fileCount = this.countFiles(projectDir)
      this.buildHistory.push({ project: projectDir, success: true, duration: buildTime, timestamp: Date.now() })
      return { success: true, buildTime, filesGenerated: fileCount }
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : String(err)
      this.buildHistory.push({ project: projectDir, success: false, duration: performance.now() - startTime, timestamp: Date.now() })
      return { success: false, error: msg, buildTime: performance.now() - startTime, filesGenerated: 0 }
    }
  }

  async buildProject(projectDir: string, steps: BuildStep[]): Promise<{ success: boolean; results: Array<{ step: string; success: boolean; output: string; duration: number }> }> {
    const { execSync } = await import("node:child_process")
    const orderedSteps = topologicalSort(steps.map((s, i) => ({ id: s.name, deps: i > 0 ? [steps[i - 1].name] : [] })))
    const results: Array<{ step: string; success: boolean; output: string; duration: number }> = []
    let allSuccess = true
    for (const stepName of orderedSteps) {
      const step = steps.find((s) => s.name === stepName)
      if (!step) continue
      const start = performance.now()
      try {
        const output = execSync(step.command, { cwd: projectDir ?? step.cwd, encoding: "utf-8", timeout: step.timeout, stdio: "pipe" })
        results.push({ step: step.name, success: true, output: output.slice(0, 2000), duration: performance.now() - start })
      } catch (err: unknown) {
        const msg = err instanceof Error ? err.message : String(err)
        results.push({ step: step.name, success: false, output: msg.slice(0, 2000), duration: performance.now() - start })
        if (step.required) { allSuccess = false; break }
      }
    }
    this.buildHistory.push({ project: projectDir, success: allSuccess, duration: results.reduce((s, r) => s + r.duration, 0), timestamp: Date.now() })
    return { success: allSuccess, results }
  }

  validateProject(projectDir: string): { valid: boolean; errors: string[]; warnings: string[] } {
    const errors: string[] = [], warnings: string[] = []
    if (!existsSync(join(projectDir, "package.json"))) errors.push("Missing package.json")
    if (!existsSync(join(projectDir, "README.md"))) warnings.push("Missing README.md")
    const srcDir = join(projectDir, "src")
    if (!existsSync(srcDir)) warnings.push("Missing src/ directory")
    const pkgPath = join(projectDir, "package.json")
    if (existsSync(pkgPath)) {
      try {
        const pkg = JSON.parse(readFileSync(pkgPath, "utf-8"))
        if (!pkg.name) errors.push("package.json missing name field")
        if (!pkg.version) warnings.push("package.json missing version field")
      } catch { errors.push("Invalid package.json") }
    }
    return { valid: errors.length === 0, errors, warnings }
  }

  getProjectStructure(projectDir: string): Array<{ path: string; type: "file" | "directory"; size: number }> {
    const entries: Array<{ path: string; type: "file" | "directory"; size: number }> = []
    const walk = (dir: string, prefix: string = "") => {
      try {
        const items = require("node:fs").readdirSync(dir, { withFileTypes: true })
        for (const item of items) {
          if (item.name === ".git" || item.name === "node_modules") continue
          const relPath = prefix ? `${prefix}/${item.name}` : item.name
          if (item.isFile()) {
            const stat = require("node:fs").statSync(join(dir, item.name))
            entries.push({ path: relPath, type: "file", size: stat.size })
          } else if (item.isDirectory()) {
            entries.push({ path: relPath, type: "directory", size: 0 })
            walk(join(dir, item.name), relPath)
          }
        }
      } catch {}
    }
    walk(projectDir)
    return entries
  }

  analyzeDependencies(projectDir: string): { direct: string[]; devDependencies: string[]; total: number } {
    const pkgPath = join(projectDir, "package.json")
    if (!existsSync(pkgPath)) return { direct: [], devDependencies: [], total: 0 }
    try {
      const pkg = JSON.parse(readFileSync(pkgPath, "utf-8"))
      const direct = Object.keys(pkg.dependencies ?? {})
      const devDependencies = Object.keys(pkg.devDependencies ?? {})
      return { direct, devDependencies, total: direct.length + devDependencies.length }
    } catch { return { direct: [], devDependencies: [], total: 0 } }
  }

  generateReadme(projectDir: string, name: string, type: string): string {
    const structure = this.getProjectStructure(projectDir)
    const deps = this.analyzeDependencies(projectDir)
    const lines = [
      `# ${name}`,
      "",
      `Auto-generated by ZYRAXON AI. Type: ${type}`,
      "",
      "## Structure",
      "",
      ...structure.slice(0, 20).map((e) => `- ${e.path}${e.type === "directory" ? "/" : ""}`),
      "",
      "## Dependencies",
      "",
      ...deps.direct.map((d) => `- ${d}`),
      "",
      `Total: ${deps.total} packages`,
    ]
    const readmePath = join(projectDir, "README.md")
    writeFileSync(readmePath, lines.join("\n"))
    return lines.join("\n")
  }

  private countFiles(dir: string): number {
    let count = 0
    try {
      const entries = require("node:fs").readdirSync(dir, { withFileTypes: true })
      for (const entry of entries) {
        if (entry.name === ".git" || entry.name === "node_modules") continue
        if (entry.isFile()) count++
        if (entry.isDirectory()) count += this.countFiles(join(dir, entry.name))
      }
    } catch {}
    return count
  }

  getGeneratedProjects(): Array<{ name: string; path: string; type: string; createdAt: number; fileCount: number }> {
    return Array.from(this.generatedProjects.entries()).map(([name, info]) => ({ name, ...info }))
  }

  getTemplateNames(): string[] { return Object.keys(TEMPLATES) }

  getBuildHistory(): Array<{ project: string; success: boolean; duration: number; timestamp: number }> {
    return [...this.buildHistory]
  }

  getBuildStats(): { totalBuilds: number; successRate: number; avgDuration: number } {
    if (this.buildHistory.length === 0) return { totalBuilds: 0, successRate: 0, avgDuration: 0 }
    const successCount = this.buildHistory.filter((b) => b.success).length
    const avgDuration = this.buildHistory.reduce((s, b) => s + b.duration, 0) / this.buildHistory.length
    return { totalBuilds: this.buildHistory.length, successRate: successCount / this.buildHistory.length, avgDuration }
  }

  async learn(toolName: string, result: unknown) {
    const resultStr = typeof result === "string" ? result : JSON.stringify(result)
    if (resultStr.includes("deploy") || resultStr.includes("create")) {
      this.generatedProjects.set(`learned-${deterministicHash(resultStr).toString(36)}`, {
        path: "", type: "unknown", createdAt: Date.now(), fileCount: 0,
      })
    }
  }
}
